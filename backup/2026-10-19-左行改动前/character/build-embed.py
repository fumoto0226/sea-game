"""Package the iframe into srcdoc so file:// opening shares the parent origin."""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parent
html = (root / 'upstream' / 'index.html').read_text()
css = (root / 'upstream' / 'style.css').read_text() + '\n' + (root / 'embed.css').read_text()
script = (root / 'upstream' / 'script.js').read_text()
# The character art is fetched at runtime, which a file:// page cannot do, so the
# bundle carries it inline. Opening the game by double-clicking is the reason the
# bundle exists at all; without this the figure never appears there.
reference = (root / 'upstream' / 'svg' / '参考.svg').read_text()
fetch_call = "fetch('./svg/参考.svg')\n  .then(response => response.text())"
assert fetch_call in script, 'reference art is no longer loaded the expected way'
script = script.replace(fetch_call, 'Promise.resolve(' + json.dumps(reference, ensure_ascii=True) + ')')

html = re.sub(r'<link rel="stylesheet"[^>]+>', '', html)
html = html.replace('</head>', '<base href="__CHARACTER_BASE__"><style>' + css + '</style></head>')
html = re.sub(r'<script src="\./script.js[^>]+></script>', lambda _: '<script>' + script + '</script>', html)
source = '// Generated by character/build-embed.py. Source files remain editable.\n'
source += '(()=>{const frame=document.querySelector(".fish-character");const html=' + json.dumps(html, ensure_ascii=True) + ';window.CHARACTER_SRCDOC=html.replace("__CHARACTER_BASE__",new URL("character/upstream/",document.baseURI).href);frame.srcdoc=window.CHARACTER_SRCDOC;})();\n'
(root / 'embed-bundle.js').write_text(source)

"""Package the iframe into srcdoc so file:// opening shares the parent origin."""
from pathlib import Path
import json
import re
root = Path(__file__).resolve().parent
html = (root / 'index.html').read_text()
css = (root / 'style.css').read_text() + '\n' + (root / 'embed.css').read_text()
script = (root / 'script.js').read_text()
html = re.sub(r'<link rel="stylesheet"[^>]+>', '', html)
html = html.replace('</head>', '<base href="__CHARACTER_BASE__"><style>' + css + '</style></head>')
html = re.sub(r'<script src="\./script.js[^>]+></script>', lambda _: '<script>' + script + '</script>', html)
source = '// Generated by character/build-embed.py. Source files remain editable.\n'
source += '(()=>{const frame=document.querySelector(".fish-character");const html=' + json.dumps(html, ensure_ascii=True) + ';window.CHARACTER_SRCDOC=html.replace("__CHARACTER_BASE__",new URL("character/",document.baseURI).href);frame.srcdoc=window.CHARACTER_SRCDOC;})();\n'
(root / 'embed-bundle.js').write_text(source)
